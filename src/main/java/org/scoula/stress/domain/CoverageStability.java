package org.scoula.stress.domain;

/**
 * 보완 가능 기간의 안정성
 * 월 순부족액은 지출과 소득의 차이라 두 값이 가까우면 아주 작아진다.
 * 이때 관측한 달을 하나만 빼도 부족과 여유가 뒤바뀔 수 있어 기간이 크게 흔들린다.
 * 길다는 이유로 숨기는 것이 아니라 부호가 뒤집히는 구간을 구분하기 위한 값이다.
 */
public enum CoverageStability {

    /** 어느 달을 빼도 월 부족 상태가 유지된다. 기간을 표시할 수 있다 */
    STABLE,

    /** 어떤 달을 빼면 월 여유로 바뀐다. 기간보다 월 부족액을 앞세운다 */
    SIGN_UNSTABLE,

    /** 애초에 기간을 계산하지 않는 상태 */
    NOT_APPLICABLE
}
